    export GNTL_TLS_CERT="$AUTO_TLS_CERT"
    export GNTL_TLS_KEY="$AUTO_TLS_KEY"
    err "Generated TLS cert/key at $TLS_DIR (self-signed)."
  else
    err "OpenSSL not found; TLS auto-generation skipped. Running without TLS."
  fi
}

terminate_pid() {
