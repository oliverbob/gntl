  PHP_BIN="$(find_php_bin || true)"
  if is_termux; then
    if [ -z "$PHP_BIN" ]; then
      err "[mobile] Installing PHP + SQLite runtime in Termux..."
      pkg update -y && pkg install -y php sqlite caddy || true
      PHP_BIN="$(find_php_bin || true)"
