open_local_app_url() {
  local url="$1"
  local attempt="${2:-1}"
  local auto_open_raw
  auto_open_raw="$(printf '%s' "$AUTO_OPEN_APP" | tr '[:upper:]' '[:lower:]')"
  if ! [[ "$auto_open_raw" =~ ^(1|true|yes|on)$ ]]; then
    return 0
  fi

  if [ -z "$url" ]; then
    return 0
  fi

  try_open_url_command() {
    local cmd="$1"
    shift
    if ! command -v "$cmd" >/dev/null 2>&1; then
      return 1
    fi
    "$cmd" "$@" >/dev/null 2>&1
  }

  if is_termux; then
    if try_open_url_command termux-open-url "$url"; then
      err "[open] Opened via termux-open-url: $url"
      return 0
    fi
    if try_open_url_command termux-open "$url"; then
      err "[open] Opened via termux-open: $url"
      return 0
    fi
    if command -v am >/dev/null 2>&1 && am start -a android.intent.action.VIEW -d "$url" >/dev/null 2>&1; then
      err "[open] Opened via Android intent (am): $url"
      return 0
    fi
  fi

  if try_open_url_command xdg-open "$url"; then
    err "[open] Opened via xdg-open: $url"
    return 0
  fi

  if try_open_url_command open "$url"; then
    err "[open] Opened via open: $url"
    return 0
  fi

  if [ "$attempt" = "1" ]; then
    err "[open] Initial browser open failed; retrying in 2s..."
    (sleep 2; open_local_app_url "$url" 2) >/dev/null 2>&1 &
    return 0
  fi

  if is_termux; then
    err "[open] Could not auto-open browser in Termux. Install/enable termux-tools and optionally Termux:API, then open manually: $url"
    return 0
  fi

  err "[open] No browser opener found. Open manually: $url"
  return 0
}

detect_lan_ip() {
  local ip=""
  if command -v hostname >/dev/null 2>&1; then
    ip="$(hostname -I 2>/dev/null | awk '{print $1}')"
  fi
  if [ -z "$ip" ] && command -v ip >/dev/null 2>&1; then
    ip="$(ip route get 1.1.1.1 2>/dev/null | awk '/src/ {for(i=1;i<=NF;i++){if($i=="src"){print $(i+1); exit}}}')"
  fi
  printf '%s' "$ip"
}

# A LAN client that gets ERR_ADDRESS_UNREACHABLE / "no route to host" on a port
# the server is listening on is almost always hitting a firewall REJECT rule.
# Detect the firewall in use and print the exact command to open the ports; never
# change firewall rules automatically.
lan_firewall_hint() {
  local ports="$*"
  local port firewall=""

  if command -v systemctl >/dev/null 2>&1 && systemctl is-active --quiet firewalld 2>/dev/null; then
    firewall="firewalld"
  fi

  # ufw.service is active on stock Ubuntu even when the firewall is off, so
  # ufw.conf (world-readable) is the authority, not the unit state.
  if [ -z "$firewall" ] && command -v ufw >/dev/null 2>&1; then
    if grep -qi '^ENABLED=yes' /etc/ufw/ufw.conf 2>/dev/null; then
      firewall="ufw"
    elif [ ! -r /etc/ufw/ufw.conf ] && command -v systemctl >/dev/null 2>&1 && systemctl is-active --quiet ufw 2>/dev/null; then
      firewall="ufw"
    fi
  fi

  if [ -z "$firewall" ] && [ "$(id -u)" -eq 0 ] && command -v iptables >/dev/null 2>&1; then
    if iptables -S INPUT 2>/dev/null | grep -qE -- '-j (REJECT|DROP)'; then
      firewall="iptables"
    fi
  fi

  if [ -z "$firewall" ] && [ -d /etc/webmin ]; then
    firewall="webmin"
  fi

  [ -n "$firewall" ] || return 0

  err "[net] ${firewall} is active. If a phone/laptop on the LAN reports the address is unreachable, open the ports:"
  case "$firewall" in
    firewalld)
      for port in $ports; do
        err "[net]   sudo firewall-cmd --permanent --add-port=${port}/tcp"
      done
      err "[net]   sudo firewall-cmd --reload"
      ;;
    ufw)
      for port in $ports; do
        err "[net]   sudo ufw allow ${port}/tcp"
      done
      ;;
    iptables)
      for port in $ports; do
        err "[net]   sudo iptables -I INPUT -p tcp --dport ${port} -j ACCEPT"
      done
      err "[net]   then persist them (netfilter-persistent save, or via Webmin)"
      ;;
    webmin)
      err "[net]   Webmin -> Networking -> Linux Firewall: allow TCP ${ports// /, }"
      ;;
  esac
}

is_termux() {
  [[ -n "${TERMUX_VERSION:-}" ]] || [[ "${PREFIX:-}" == *"com.termux"* ]] || command -v termux-info >/dev/null 2>&1
}

is_android_kernel() {
  [[ -n "${ANDROID_ROOT:-}" ]] || [[ -n "${ANDROID_DATA:-}" ]] || \
    grep -qi "android" /proc/version 2>/dev/null || \
    (command -v getprop >/dev/null 2>&1 && getprop ro.build.version.release >/dev/null 2>&1)
}

is_ish_ios() {
  [[ -f /etc/alpine-release ]] && grep -qi "ish\|ios" /proc/version 2>/dev/null
}

is_mobile_runtime() {
  is_termux || is_ish_ios || is_android_kernel
}

is_debian_like() {
  if is_mobile_runtime; then
    return 1
  fi
  [ -r /etc/os-release ] && grep -Eqi '^(ID|ID_LIKE)=.*(debian|ubuntu)' /etc/os-release
}

is_ubuntu_host() {
  is_debian_like && grep -Eqi '^(ID|ID_LIKE)=.*ubuntu' /etc/os-release
}

# Run a command as root when possible. Output/prompts stay visible so a sudo
# password request never looks like a hang.
maybe_sudo() {
  if [ "$(id -u)" -eq 0 ]; then
    "$@"
    return $?
  fi
  if command -v sudo >/dev/null 2>&1; then
    err "[host] Requesting sudo for: $*"
    sudo "$@"
    return $?
  fi
  err "[host] Root privileges required but sudo is unavailable: $*"
  return 127
}

node_major_version() {
  local bin raw
  bin="${1:-node}"
  raw="$("$bin" -v 2>/dev/null || true)"
  [ -n "$raw" ] || return 1
  printf '%s' "${raw#v}" | cut -d. -f1
}

node_is_supported() {
  local major
  major="$(node_major_version 2>/dev/null || true)"
  [ -n "$major" ] || return 1
  [ "$major" -ge "$NODE_MIN_MAJOR" ] 2>/dev/null
}

# A previously installed project-local Node, plus nvm/fnm installs that are not
# on PATH for non-login shells: adopt them before concluding Node is missing.
adopt_user_node_install() {
  if command -v node >/dev/null 2>&1 && command -v npm >/dev/null 2>&1 && node_is_supported; then
    return 0
  fi

  # A project-local Node only wins when the system cannot supply a usable one.
  local local_major=""
  local_major="$(node_major_version "$LOCAL_NODE_DIR/bin/node" 2>/dev/null || true)"
  if [ -n "$local_major" ] && [ "$local_major" -ge "$NODE_MIN_MAJOR" ] 2>/dev/null; then
    use_local_node && return 0
  fi

  if command -v node >/dev/null 2>&1 && command -v npm >/dev/null 2>&1; then
    return 0
  fi

  local nvm_dir candidate
  nvm_dir="${NVM_DIR:-$HOME/.nvm}"
  if [ -s "$nvm_dir/nvm.sh" ]; then
    # shellcheck disable=SC1090,SC1091
    . "$nvm_dir/nvm.sh" >/dev/null 2>&1 || true
    hash -r 2>/dev/null || true
  fi

  if ! command -v node >/dev/null 2>&1 && [ -d "$nvm_dir/versions/node" ]; then
    candidate="$(find "$nvm_dir/versions/node" -maxdepth 2 -type f -name node -perm -u+x 2>/dev/null | sort -V | tail -n1)"
    if [ -n "$candidate" ]; then
      PATH="$(dirname "$candidate"):$PATH"
      export PATH
      hash -r 2>/dev/null || true
    fi
  fi

  if ! command -v node >/dev/null 2>&1 && [ -x "$HOME/.local/share/fnm/aliases/default/bin/node" ]; then
    PATH="$HOME/.local/share/fnm/aliases/default/bin:$PATH"
    export PATH
    hash -r 2>/dev/null || true
  fi

  command -v node >/dev/null 2>&1 && command -v npm >/dev/null 2>&1
}

find_php_bin() {
  if [ -n "${GNTL_PHP_BIN:-}" ]; then
    if command -v "$GNTL_PHP_BIN" >/dev/null 2>&1; then
      command -v "$GNTL_PHP_BIN"
      return 0
    fi
    if [ -x "$GNTL_PHP_BIN" ]; then
      echo "$GNTL_PHP_BIN"
      return 0
    fi
    err "[mobile] GNTL_PHP_BIN is set but not executable/found: $GNTL_PHP_BIN"
  fi
  local candidate
  for candidate in php php84 php83 php82 php81; do
    if command -v "$candidate" >/dev/null 2>&1; then
      command -v "$candidate"
      return 0
    fi
  done
  return 1
}

