ensure_and_load_env_defaults() {
  local mobile_caddy_key_pattern mobile_auth_key_pattern
  mobile_caddy_key_pattern='^[[:space:]]*GNTL_MOBILE_USE_CADDY='
  mobile_auth_key_pattern='^[[:space:]]*GNTL_MOBILE_REQUIRE_AUTH='

  if [ ! -f "$ENV_FILE" ]; then
    cat > "$ENV_FILE" <<'EOF'
# Auto-generated by run.sh
GNTL_MOBILE_USE_CADDY=1
GNTL_MOBILE_REQUIRE_AUTH=1
EOF
    err "[config] Created .env with default mobile settings"
  else
    if ! grep -Eq "$mobile_caddy_key_pattern" "$ENV_FILE" 2>/dev/null; then
      printf '\nGNTL_MOBILE_USE_CADDY=1\n' >> "$ENV_FILE"
      err "[config] Added GNTL_MOBILE_USE_CADDY=1 to .env"
    fi
    if ! grep -Eq "$mobile_auth_key_pattern" "$ENV_FILE" 2>/dev/null; then
      printf '\nGNTL_MOBILE_REQUIRE_AUTH=1\n' >> "$ENV_FILE"
      err "[config] Added GNTL_MOBILE_REQUIRE_AUTH=1 to .env"
    fi
  fi

  if [ -f "$ENV_FILE" ]; then
    set -a
    . "$ENV_FILE"
    set +a
  fi
}

